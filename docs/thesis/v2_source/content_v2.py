    "Cutting a city's carbon emissions requires knowing where in the city combustion is concentrated and which "
    "intervention works before it is implemented. Tehran has no measured neighbourhood-scale CO2 map, and global emission "
    "products are either coarse or built from proxy layers. Earlier studies mostly reproduced a modelled product, compared "
    "graph models with baselines that see a smaller neighbourhood, and rarely tested reinforcement learning against strong "
    "static policies. This thesis builds an integrated framework for Tehran that predicts combustion hotspots from "
    "traffic, energy and pollution data and evaluates emission-reduction policies in a simulator before implementation. "
    "A bottom-up emission inventory and a four-step traffic model were built, and the TROPOMI NO2 column served as a "
    "target independent of the inventory. Fusion models and graph neural networks were compared with traditional models "
    "under 22-km spatial block cross-validation and on the held-out year 1404. The graph model served as the exposure "
    "model of a 22-district simulator, in which a reinforcement learning agent was evaluated against tuned static "
    "policies.",
    "Fusing the three data domains gave no conclusive gain over the best single domain. The graph network beat "
    "traditional models with small windows but not spatial-lag models with the same reach: skill rose steeply up to about "
    "12 km and saturated before the 24-km correlation length of the target, and on 1404 a linear regression with a 23-km "
    "window reached a Spearman correlation of 0.929 against 0.933 for the graph network. With a budget of 30 restriction "
    "days, the daily agent beat the pre-specified static policies, but a simple rule that restricts the districts with "
    "the most incoming car-kilometres returned about 50% more. Choosing a policy by simulation improved the worst 10% of "
    "outcomes over choosing without simulation. For mapping combustion hotspots, a model's reach matters more than the "
    "graph architecture; for traffic policy, a mild, continuous restriction in the high-traffic districts 2, 3 and 6 "
    "outperforms short, severe restrictions. Both findings emerged only against simple baselines and through simulation "
    "before implementation.",
